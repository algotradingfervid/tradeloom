package ta

// Shared sine/cosine for the dominant-cycle-phase DFT in HT_DCPHASE, HT_SINE
// and HT_TRENDMODE.
//
// The DFT evaluates sin and cos only at x = i*2*pi/n for 0 <= i < n <= 50
// (n is DCPeriodInt, which the Hilbert code clamps to at most 50). On inputs
// with no cycle (flat prices, a period-2 zigzag) realPart and imagPart cancel
// to rounding noise, so atan(realPart/imagPart) is decided by the last ulp of
// each sin/cos term. Go's math.Sin/math.Cos differ from the C library's libm in
// the last ulp for about a quarter of these 1275 angles, so the libm values are
// tabulated here and Go reproduces TA-Lib exactly.
//
// The table was generated on macOS arm64 by a C program that computes
// x = (double)i * (atan(1)*8.0) / (double)n exactly as the TA-Lib loop does
// and calls sin(x) and cos(x), compiled with clang -O2 -ffp-contract=off (the
// TA-Lib build flags), so the pair is computed by the same __sincos_stret call
// TA-Lib's objects use. On real price data these values match math.Sin/Cos to
// within one ulp; the table only matters for degenerate inputs.

const (
	htTrigMaxN = 50
	htTrigLen  = htTrigMaxN * (htTrigMaxN + 1) / 2
)

// htSinCos returns sin(x) and cos(x) for the DFT angle x = i*2*pi/n, where
// the caller computed x exactly as C does. n outside [1, 50] cannot occur for
// finite input; it falls back to math.Sin/math.Cos.
func htSinCos(i, n int, x float64) (float64, float64) {
	if n < 1 || n > htTrigMaxN || i < 0 || i >= n {
		return libmSin(x), libmCos(x)
	}
	v := htTrigTable[n*(n-1)/2+i]
	return v[0], v[1]
}

