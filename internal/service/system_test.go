type fakeFeedCtl struct{ reconnects int }

func (f *fakeFeedCtl) Reconnect() { f.reconnects++ }

const sampleNotices = "# Third-party notices\n\nGenerated by make notices.\n\n" +
	"## github.com/wailsapp/wails/v2 v2.16.0 — MIT\n\n```\nMIT License\n```\n\n" +
	"## modernc.org/sqlite v1.50.0 — BSD-3-Clause\n\n```\nCopyright\n```\n\n" +
	"## modernc.org/mathutil v1.7.1 — BSD-3-Clause\n\n```\nCopyright\n```\n\n" +
	"# npm production dependencies (frontend/)\n\n" +
	"[react@18.3.1](https://github.com/facebook/react) - MIT\n" +
	"[scheduler@0.23.2](https://github.com/facebook/react) - MIT\n"

func TestParseNotices(t *testing.T) {
	got := ParseNotices([]byte(sampleNotices))
	want := []Licence{
		{Name: "github.com/wailsapp/wails/v2", Version: "v2.16.0", Licence: "MIT"},
		{Name: "modernc.org/sqlite", Version: "v1.50.0", Licence: "BSD-3-Clause"},
		{Name: "modernc.org/mathutil", Version: "v1.7.1", Licence: "BSD-3-Clause"},
		{Name: "react", Version: "18.3.1", Licence: "MIT"},
		{Name: "scheduler", Version: "0.23.2", Licence: "MIT"},
	}
	if len(got) != len(want) {
		t.Fatalf("%d licences, want %d: %+v", len(got), len(want), got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("[%d] %+v want %+v", i, got[i], want[i])
		}
	}
	if n := ParseNotices(nil); len(n) != 0 {
		t.Fatalf("nil notices: %+v", n)
	}
}

func TestAppInfo_Status_ReconnectFeed(t *testing.T) {
	e := newSvcEnv(t)
	layout := store.NewLayout(t.TempDir())
	e.svc.d.Layout, e.svc.d.AppVersion, e.svc.d.DB = layout, "0.3.0", storetest.Open(t)
	e.svc.d.Licences = []byte(sampleNotices)
	e.svc.d.Calendar = mustCalendar(t)
	ctx := context.Background()
	info := e.svc.AppInfo(ctx)
	if info.Version != "0.3.0" || !strings.HasPrefix(info.Build, "go1.") || info.SchemaVersion != store.SupportedSchema() || info.DataDir != layout.Root || len(info.Licences) != 5 {
		t.Fatalf("%+v", info)
	}
	st := e.svc.Status(ctx)
	if st.Feed.State != "stopped" || st.Market.Exchange != "NSE" || st.Market.Phase != "continuous" || st.Market.AtMs != e.clock.Now().UnixMilli() {
		t.Fatalf("%+v", st)
	}
	e.svc.rememberFeed(ticker.FeedState{State: "live", Connections: 1, Tokens: 3})
	if st := e.svc.Status(ctx); st.Feed.State != "live" || st.Feed.Tokens != 3 {
		t.Fatalf("%+v", st.Feed)
	}
	fc := &fakeFeedCtl{}
	e.svc.d.FeedCtl = fc
	e.session.setState(kite.SessionState{State: kite.StateLoggedOut})
	if err := e.svc.ReconnectFeed(ctx); refusedCode(t, err) != "not_logged_in" {
		t.Fatal(err)
	}
	e.session.setState(kite.SessionState{State: kite.StateReady, DataPlan: kite.PlanConnect})
	if err := e.svc.ReconnectFeed(ctx); err != nil || fc.reconnects != 1 {
		t.Fatalf("%v %d", err, fc.reconnects)
	}
	e.svc.d.FeedCtl = nil
	var r *ErrRefused
	if err := e.svc.ReconnectFeed(ctx); !errors.As(err, &r) || r.Code != "unavailable" {
		t.Fatalf("%v", err)
	}
}

// The generated file embeds full licence texts in ``` fences; headings inside them (modernc.org/libc ships
// "## Go", "## musl libc", …) are not components. scripts/gen-notices.sh also writes npm packages as
// "## <name> <version> — <licence>" sections (scoped names included).
func TestParseNotices_IgnoresFencedLicenceText(t *testing.T) {
	md := "## modernc.org/libc v1.75.7 — MIT\n\n```\n# Third-Party Software Notices\n\n## Go — BSD-3-Clause\n" +
		"[fake@1.0.0](https://example.com) - MIT\n```\n\n# npm production dependencies (frontend/)\n\n" +
		"## @types/react 19.3.0 — MIT\n\n```\n    MIT License\n```\n"
	got := ParseNotices([]byte(md))
	want := []Licence{
		{Name: "modernc.org/libc", Version: "v1.75.7", Licence: "MIT"},
		{Name: "@types/react", Version: "19.3.0", Licence: "MIT"},
	}
	if len(got) != len(want) || got[0] != want[0] || got[1] != want[1] {
		t.Fatalf("%+v want %+v", got, want)
	}
}
