type fakeFeedCtl struct{ reconnects int }

func (f *fakeFeedCtl) Reconnect() { f.reconnects++ }

const sampleNotices = "# Third-party notices\n\nGenerated by make notices.\n\n" +
	"## github.com/wailsapp/wails/v2 v2.16.0 — MIT\n\n```\nMIT License\n```\n\n" +
	"## modernc.org/sqlite v1.50.0 — BSD-3-Clause\n\n```\nCopyright\n```\n\n" +
	"## modernc.org/mathutil v1.7.1 — BSD-3-Clause\n\n```\nCopyright\n```\n\n" +
	"# npm production dependencies (frontend/)\n\n" +
	"[react@18.3.1](https://github.com/facebook/react) - MIT\n" +
	"[scheduler@0.23.2](https://github.com/facebook/react) - MIT\n"

func TestParseNotices(t *testing.T) {
	got := ParseNotices([]byte(sampleNotices))
	want := []Licence{
		{Name: "github.com/wailsapp/wails/v2", Version: "v2.16.0", Licence: "MIT"},
		{Name: "modernc.org/sqlite", Version: "v1.50.0", Licence: "BSD-3-Clause"},
		{Name: "modernc.org/mathutil", Version: "v1.7.1", Licence: "BSD-3-Clause"},
		{Name: "react", Version: "18.3.1", Licence: "MIT"},
		{Name: "scheduler", Version: "0.23.2", Licence: "MIT"},
	}
	if len(got) != len(want) {
		t.Fatalf("%d licences, want %d: %+v", len(got), len(want), got)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Fatalf("[%d] %+v want %+v", i, got[i], want[i])
		}
	}
	if n := ParseNotices(nil); len(n) != 0 {
		t.Fatalf("nil notices: %+v", n)
	}
}

func TestAppInfo_Status_ReconnectFeed(t *testing.T) {
	e := newSvcEnv(t)
	layout := store.NewLayout(t.TempDir())
	e.svc.d.Layout, e.svc.d.AppVersion, e.svc.d.DB = layout, "0.3.0", storetest.Open(t)
	e.svc.d.Licences = []byte(sampleNotices)
	e.svc.d.Calendar = mustCalendar(t)
	ctx := context.Background()
	info := e.svc.AppInfo(ctx)
	if info.Version != "0.3.0" || !strings.HasPrefix(info.Build, "go1.") || info.SchemaVersion != store.SupportedSchema() || info.DataDir != layout.Root || len(info.Licences) != 5 {
		t.Fatalf("%+v", info)
	}
	st := e.svc.Status(ctx)
	if st.Feed.State != "stopped" || st.Market.Exchange != "NSE" || st.Market.Phase != "continuous" || st.Market.AtMs != e.clock.Now().UnixMilli() {
		t.Fatalf("%+v", st)
	}
	e.svc.rememberFeed(ticker.FeedState{State: "live", Connections: 1, Tokens: 3})
	if st := e.svc.Status(ctx); st.Feed.State != "live" || st.Feed.Tokens != 3 {
		t.Fatalf("%+v", st.Feed)
	}
	fc := &fakeFeedCtl{}
	e.svc.d.FeedCtl = fc
	e.session.setState(kite.SessionState{State: kite.StateLoggedOut})
	if err := e.svc.ReconnectFeed(ctx); refusedCode(t, err) != "not_logged_in" {
		t.Fatal(err)
	}
	e.session.setState(kite.SessionState{State: kite.StateReady, DataPlan: kite.PlanConnect})
	if err := e.svc.ReconnectFeed(ctx); err != nil || fc.reconnects != 1 {
		t.Fatalf("%v %d", err, fc.reconnects)
	}
	e.svc.d.FeedCtl = nil
	var r *ErrRefused
	if err := e.svc.ReconnectFeed(ctx); !errors.As(err, &r) || r.Code != "unavailable" {
		t.Fatalf("%v", err)
	}
}

// The generated file embeds full licence texts in ``` fences; headings inside them (modernc.org/libc ships
// "## Go", "## musl libc", …) are not components. scripts/gen-notices.sh also writes npm packages as
// "## <name> <version> — <licence>" sections (scoped names included).
func TestParseNotices_IgnoresFencedLicenceText(t *testing.T) {
	md := "## modernc.org/libc v1.75.7 — MIT\n\n```\n# Third-Party Software Notices\n\n## Go — BSD-3-Clause\n" +
		"[fake@1.0.0](https://example.com) - MIT\n```\n\n# npm production dependencies (frontend/)\n\n" +
		"## @types/react 19.3.0 — MIT\n\n```\n    MIT License\n```\n"
	got := ParseNotices([]byte(md))
	want := []Licence{
		{Name: "modernc.org/libc", Version: "v1.75.7", Licence: "MIT"},
		{Name: "@types/react", Version: "19.3.0", Licence: "MIT"},
	}
	if len(got) != len(want) || got[0] != want[0] || got[1] != want[1] {
		t.Fatalf("%+v want %+v", got, want)
	}
}

// Only an exact column-0 ``` toggles the fence: an indented ``` inside a licence text does not end it, and
// an empty input still yields a non-nil (JSON []) slice.
func TestParseNotices_ExactFenceAndNonNil(t *testing.T) {
	md := "## a.example/m v1.0.0 — MIT\n\n```\nText\n    ```\n## evil v6.6.6 — MIT\n ```\n```\n\n## b.example/m v2.0.0 — ISC\n"
	got := ParseNotices([]byte(md))
	want := []Licence{{Name: "a.example/m", Version: "v1.0.0", Licence: "MIT"}, {Name: "b.example/m", Version: "v2.0.0", Licence: "ISC"}}
	if len(got) != len(want) || got[0] != want[0] || got[1] != want[1] {
		t.Fatalf("%+v want %+v", got, want)
	}
	for _, in := range [][]byte{nil, []byte("# nothing here\n")} {
		l := ParseNotices(in)
		if l == nil {
			t.Fatalf("ParseNotices(%q) is nil", in)
		}
		if b, _ := json.Marshal(l); string(b) != "[]" {
			t.Fatalf("ParseNotices(%q) marshals to %s", in, b)
		}
	}
}

// Status carries ms-only DTOs (Ruling 71): non-zero NextRetry/LastTick and the clock offset's UpdatedAt
// become Unix ms, and no time.Time reaches the JSON.
func TestStatus_DTOsAreUnixMs(t *testing.T) {
	e := newSvcEnv(t)
	e.svc.d.Calendar = mustCalendar(t)
	retry, last, upd := ist(2026, 10, 12, 10, 1), ist(2026, 10, 12, 9, 59), ist(2026, 10, 12, 9, 58)
	e.svc.rememberFeed(ticker.FeedState{State: "reconnecting", Attempt: 2, NextRetry: retry, LastTick: last, Connections: 1, Tokens: 4})
	e.clock.SetOffset(clock.Offset{Value: 1500 * time.Millisecond, Millis: 1500, Source: clock.SourceTicks, Samples: 7, Warn: true, UpdatedAt: upd})
	st := e.svc.Status(context.Background())
	if want := (FeedStateDTO{State: "reconnecting", Attempt: 2, NextRetryMs: retry.UnixMilli(), LastTickMs: last.UnixMilli(), Connections: 1, Tokens: 4}); st.Feed != want {
		t.Fatalf("feed %+v want %+v", st.Feed, want)
	}
	if want := (OffsetDTO{Millis: 1500, Source: "ticks", Samples: 7, Warn: true, UpdatedAtMs: upd.UnixMilli()}); st.Clock != want {
		t.Fatalf("clock %+v want %+v", st.Clock, want)
	}
	b, err := json.Marshal(st)
	if err != nil {
		t.Fatal(err)
	}
	for _, bad := range []string{`"nextRetry"`, `"lastTick"`, `"updatedAt"`, "2026-10-12T"} {
		if strings.Contains(string(b), bad) {
			t.Fatalf("status JSON contains %s: %s", bad, b)
		}
	}
}

// A data plan that cannot carry a feed (Personal plan, or the probe not finished) refuses "unavailable"
// without touching the feed.
func TestReconnectFeed_NoFeedPlan(t *testing.T) {
	e := newSvcEnv(t)
	fc := &fakeFeedCtl{}
	e.svc.d.FeedCtl = fc
	for _, p := range []kite.DataPlan{kite.PlanNone, kite.PlanUnknown} {
		e.session.setState(kite.SessionState{State: kite.StateReady, DataPlan: p})
		if err := e.svc.ReconnectFeed(context.Background()); refusedCode(t, err) != "unavailable" {
			t.Fatalf("%s: %v", p, err)
		}
	}
	if fc.reconnects != 0 {
		t.Fatalf("reconnects = %d", fc.reconnects)
	}
}

// rememberFeed (the feed.state forwarder) and Status (a binding call) run concurrently; -race covers it.
func TestStatus_ConcurrentWithRememberFeed(t *testing.T) {
	e := newSvcEnv(t)
	e.svc.d.Calendar = mustCalendar(t)
	var wg sync.WaitGroup
	wg.Add(2)
	go func() {
		defer wg.Done()
		for i := 0; i < 200; i++ {
			e.svc.rememberFeed(ticker.FeedState{State: "live", Tokens: i})
		}
	}()
	go func() {
		defer wg.Done()
		for i := 0; i < 200; i++ {
			if st := e.svc.Status(context.Background()); st.Feed.State != "stopped" && st.Feed.State != "live" {
				t.Errorf("state %q", st.Feed.State)
			}
		}
	}()
	wg.Wait()
	if st := e.svc.Status(context.Background()); st.Feed.Tokens != 199 {
		t.Fatalf("last feed %+v", st.Feed)
	}
}

